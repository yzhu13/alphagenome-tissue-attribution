"""
step45_aggregation_variants.py

Two further aggregation checks:

1. Is the eye hub specific to our original, non-recommended scorer (501 bp DIFF_MEAN)? Pool the RAW
   scores of AlphaGenome's RECOMMENDED scorers (DNase/ATAC DIFF_LOG2_SUM, RNA-seq GeneMaskLFC) per
   tissue, as the original pipeline did, and rank tissues.
2. The AlphaGenome team recommends, for single-variant prioritisation, the MAXIMUM quantile score
   across tracks/modalities (community forum, 8 May 2026). Applied per tissue (max |q| over the tissue's
   tracks, averaged over loci), does it rank tissues by biology or by how many tracks they have?

Uses the step42 matrix cache and step35's locus-tissue table. Writes reports/aggregation_variants.md.

    python scripts/step45_aggregation_variants.py
"""
import os
import sys

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import step35_analysis as s35  # noqa: E402
import step42_uncertainty as s42  # noqa: E402

REPORT = os.path.join(s35.NEW, "reports", "aggregation_variants.md")
DOMAINS = ["eye", "kidney", "metabolic", "null"]


def main():
    v = s35.read_variants()
    dom = s35.domain_map(v)
    lt = pd.read_parquet(os.path.join(s35.AN, "locus_tissue.parquet"))
    pub = s35.as_published(lt)
    M = s42.build_matrices()
    L = ["# Aggregation variants", "",
         "Generated by `scripts/step45_aggregation_variants.py`. 12 ranked tissues (`other` excluded).", ""]

    rows = []
    for d in DOMAINS:
        ids = set(dom.loc[dom.domain == d, "id"])
        x = pub[(pub.scorer == "rec_all") & pub.id.isin(ids) & (pub.tissue != "other")]
        s = x.groupby("tissue").abs_raw.mean().sort_values(ascending=False)
        rows.append({"loci": d, "eye rank": list(s.index).index("eye") + 1, "top": s.index[0],
                     "top / next": round(s.iloc[0] / s.iloc[1], 2)})
    os.makedirs(s35.AN, exist_ok=True)
    pd.DataFrame(rows).to_csv(os.path.join(s35.AN, "step45_raw_recommended_pooled.csv"), index=False)
    L += ["## 1. Raw scores of the RECOMMENDED scorers, pooled over DNase + ATAC + RNA-seq (eye as in the original pipeline)", "",
          "If the hub came only from our non-recommended DIFF_MEAN scorer, the eye should not lead here.", "",
          pd.DataFrame(rows).to_markdown(index=False), ""]

    rows, per_tissue = [], []
    for d in DOMAINS:
        ids = set(dom.loc[dom.domain == d, "id"])
        for lab, sc in [("all recommended scorers pooled", s35.REC), ("DNase only", ["dnase_rec"])]:
            X, rid, tis = s42.select(M, "q", sc, False)
            X = X[np.isin(rid, list(ids))]
            score = pd.Series({t: np.nanmax(X[:, tis == t], axis=1).mean() for t in np.unique(tis)})
            ntr = pd.Series({t: int((tis == t).sum()) for t in np.unique(tis)})
            s = score.sort_values(ascending=False)
            per_tissue.append(pd.DataFrame({"loci": d, "tracks": lab, "tissue": score.index, "max_q": score.values,
                                            "n_tracks": ntr[score.index].values}))
            rows.append({"loci": d, "tracks": lab, "eye rank": list(s.index).index("eye") + 1, "top": s.index[0],
                         "Spearman(score, n tracks)": round(spearmanr(score, ntr[score.index]).correlation, 2),
                         "eye tracks": ntr["eye"], "top tissue tracks": ntr[s.index[0]]})
    pd.DataFrame(rows).to_csv(os.path.join(s35.AN, "step45_max_per_tissue_summary.csv"), index=False)
    pd.concat(per_tissue).to_csv(os.path.join(s35.AN, "step45_max_per_tissue_scores.csv"), index=False)
    L += ["## 2. Max |quantile score| over each tissue's tracks, averaged over loci", "",
          "The maximum of more draws is larger, so this ranks tissues by track count.", "",
          pd.DataFrame(rows).to_markdown(index=False), ""]

    with open(REPORT, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {REPORT}")


if __name__ == "__main__":
    main()
