"""
step48_enformer_analysis.py

Does the AlphaGenome failure mode replicate in Enformer? Uses the scores from step47 and the track
map from enformer_tissue_map.py. 12 tissues (`other` excluded); assays DNase (incl. 10 ATAC), CAGE,
ChIP (histone + TF).

  E1  scale: median |raw effect| per assay for null variants; share of per-track variance explained
      by assay vs by tissue (as A2 for AlphaGenome)
  E2  raw effects pooled over all assays per tissue (the original-pipeline approach): ranks for each
      domain and for null variants, and Spearman of tissue score with each tissue's assay shares
  E3  null-calibrated (per-track percentile among the null variants; leave-one-out for nulls),
      pooled: mean percentile per assay for GWAS loci (does one assay depart more?) and tissue ranks
  E4  calibrated, within DNase and within CAGE: mean percentile and strong-effect fraction
      (>= 0.95); expected-tissue ranks; bootstrap over loci and tracks (P rank 1)
  E5  max over each tissue's tracks vs track count

Raw effect = |alt - ref| of predicted coverage summed over the central 512 bp.
Writes reports/enformer_validation.md and data/enformer/step48_*.csv.

    python scripts/step48_enformer_analysis.py
"""
import glob
import os
import sys

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import enformer_tissue_map as etm  # noqa: E402
import step35_analysis as s35  # noqa: E402

EN = os.path.join(s35.NEW, "data", "enformer")
REPORT = os.path.join(s35.NEW, "reports", "enformer_validation.md")
DOMAINS = ["eye", "kidney", "metabolic"]
N_BOOT, SEED = 500, 0


def load():
    p = pd.read_csv(os.path.join(EN, "variants_enformer.csv"), keep_default_na=False)
    ids, R, flags = [], [], []
    for f in sorted(glob.glob(os.path.join(EN, "scores", "*.npz"))):
        z = np.load(f)
        ids.append(os.path.basename(f)[:-4])
        R.append(np.abs(z["alt_c"] - z["ref_c"]))
        flags.append(str(z["flag"]))
    R = np.vstack(R)
    meta = p.set_index("id").loc[ids].reset_index()
    meta["flag"] = flags
    tracks = etm.build()
    return meta, R, tracks


def calibrate(R, is_null):
    """Per-track mid-rank percentile among null variants; nulls are scored leave-one-out."""
    N = np.sort(R[is_null], axis=0)
    n = N.shape[0]
    P = np.empty_like(R, dtype=np.float32)
    for j in range(R.shape[1]):
        lo = np.searchsorted(N[:, j], R[:, j], "left")
        hi = np.searchsorted(N[:, j], R[:, j], "right")
        P[:, j] = (lo + hi) / (2 * n)
    # leave-one-out for nulls: remove the variant itself (it counts as one tie)
    P[is_null] = (P[is_null] * 2 * n - 1) / (2 * (n - 1))
    return P


def tissue_score(X, tr, cols, stat="mean"):
    """Mean over tracks (within tissue) of the mean over variants."""
    v = X[:, cols]
    colmean = v.mean(0) if stat == "mean" else v.max(1) if stat == "max" else None
    t = tr.iloc[cols]
    return pd.Series(colmean, index=t.index).groupby(t.tissue.values).mean()


def ranks(s):
    return s.rank(ascending=False, method="min").astype(int)


def max_per_tissue(X, tr, cols):
    t = tr.iloc[cols].reset_index(drop=True)
    out = {}
    for tis, g in t.groupby("tissue"):
        out[tis] = X[:, np.asarray(cols)[g.index.values]].max(1).mean()
    return pd.Series(out)


def boot_p1(X, tr, cols, n_boot=N_BOOT, seed=SEED):
    rng = np.random.default_rng(seed)
    t = tr.iloc[cols].reset_index(drop=True)
    groups = {tis: np.asarray(cols)[g.index.values] for tis, g in t.groupby("tissue")}
    wins = {k: 0 for k in groups}
    for _ in range(n_boot):
        rows = rng.integers(0, X.shape[0], X.shape[0])
        colmean = X[rows].mean(0)
        sc = {k: colmean[rng.choice(c, len(c))].mean() for k, c in groups.items()}
        wins[max(sc, key=sc.get)] += 1
    return pd.Series(wins) / n_boot


def main():
    meta, R, tracks = load()
    tr = tracks.set_index("index").loc[np.arange(R.shape[1])].reset_index()
    keep = np.where(tr.tissue != "other")[0]
    is_null = (meta.pick_domain == "null").values
    dom_rows = {d: (meta.pick_domain == d).values for d in DOMAINS + ["null"]}
    L = ["# Enformer validation", "",
         "Generated by `scripts/step48_enformer_analysis.py`. Scores from `step47_enformer_scoring.py` "
         "(Enformer, PyTorch port, CPU). Raw effect = |alt − ref| of predicted coverage summed over the central "
         "512 bp. 12 tissues; `other` (cell lines, stem-cell derived, treated) excluded.", "",
         f"Variants scored: {len(meta)} ({', '.join(f'{d} {int(m.sum())}' for d, m in dom_rows.items())}); "
         f"allele check: {meta.flag.value_counts().to_dict()}.", ""]

    # composition
    comp = tr.iloc[keep].pivot_table(index="tissue", columns="assay", values="index", aggfunc="count", fill_value=0)
    comp["n"] = comp.sum(1)
    for a in ["CAGE", "CHIP", "DNASE"]:
        comp[f"share_{a}"] = comp[a] / comp.n
    L += ["## Track composition", "", comp.round(2).to_markdown(), ""]

    # E1 scale and variance decomposition
    med = {a: float(np.median(R[is_null][:, keep[tr.iloc[keep].assay.values == a]])) for a in ["DNASE", "CAGE", "CHIP"]}
    tm = pd.DataFrame({"y": np.log10(R[is_null][:, keep].mean(0) + 1e-6), "assay": tr.iloc[keep].assay.values,
                       "tissue": tr.iloc[keep].tissue.values})
    tot = ((tm.y - tm.y.mean()) ** 2).sum()
    r2 = {k: 1 - ((tm.y - tm.groupby(k).y.transform("mean")) ** 2).sum() / tot for k in ["assay", "tissue"]}
    pd.DataFrame([{"median_abs_raw_DNASE": med["DNASE"], "median_abs_raw_CAGE": med["CAGE"],
                   "median_abs_raw_CHIP": med["CHIP"], "CHIP/DNASE": med["CHIP"] / med["DNASE"],
                   "CHIP/CAGE": med["CHIP"] / med["CAGE"], "var_explained_assay": r2["assay"],
                   "var_explained_tissue": r2["tissue"]}]).to_csv(os.path.join(EN, "step48_scale.csv"), index=False)
    L += ["## E1. Scale", "", "Median |raw effect| among null variants: " +
          ", ".join(f"{a} {v:.4g}" for a, v in med.items()) +
          f" (DNase/CAGE {med['DNASE'] / med['CAGE']:.1f}x, DNase/ChIP {med['DNASE'] / med['CHIP']:.1f}x).", "",
          f"Share of variance in per-track mean log10 |raw effect| (null variants) explained by assay "
          f"{r2['assay']:.1%}, by tissue {r2['tissue']:.1%}.", ""]

    # E2 raw pooled
    rows = []
    for d, m in dom_rows.items():
        s = tissue_score(R[m], tr, keep)
        rk = ranks(s)
        top2 = s.sort_values(ascending=False)
        row = {"loci": d, "top": top2.index[0], "top / next": top2.iloc[0] / top2.iloc[1], "eye rank": rk["eye"]}
        for a in ["DNASE", "CAGE", "CHIP"]:
            row[f"ρ with {a} share"] = spearmanr(s, comp.loc[s.index, f"share_{a}"]).correlation
        row["P_boot(top #1)"] = boot_p1(R[m], tr, keep)[top2.index[0]]
        rows.append(row)
        pd.DataFrame({"score": s, "rank": rk}).to_csv(os.path.join(EN, f"step48_raw_pooled_{d}.csv"))
    e2 = pd.DataFrame(rows)
    e2.to_csv(os.path.join(EN, "step48_raw_pooled_summary.csv"), index=False)
    L += ["## E2. Raw effects pooled over all assays (the original pipeline, applied to Enformer)", "",
          e2.round(3).to_markdown(index=False), ""]

    # E3 calibrated pooled
    P = calibrate(R, is_null)
    ex = []
    for d in DOMAINS:
        m = dom_rows[d]
        row = {"loci": d}
        for a in ["DNASE", "CAGE", "CHIP"]:
            row[f"mean pct {a}"] = float(P[m][:, keep[tr.iloc[keep].assay.values == a]].mean())
        s = tissue_score(P[m], tr, keep)
        pd.DataFrame({"score": s, "rank": ranks(s)}).to_csv(os.path.join(EN, f"step48_cal_pooled_{d}.csv"))
        row["pooled: top"] = s.idxmax()
        row["pooled: eye rank"] = ranks(s)["eye"]
        row["pooled: ρ with CHIP share"] = spearmanr(s, comp.loc[s.index, "share_CHIP"]).correlation
        ex.append(row)
    e3 = pd.DataFrame(ex)
    e3.to_csv(os.path.join(EN, "step48_calibrated_pooled.csv"), index=False)
    L += ["## E3. Null-calibrated, pooled over assays", "",
          "Null variants score 0.5 on every track by construction.", "", e3.round(3).to_markdown(index=False), ""]

    # E4 within assay
    out = []
    for a in ["DNASE", "CAGE"]:
        cols = keep[tr.iloc[keep].assay.values == a]
        for metric in ["mean pct", "strong fraction"]:
            X = P if metric == "mean pct" else (P >= 0.95).astype(np.float32)
            for d in DOMAINS:
                s = tissue_score(X[dom_rows[d]], tr, cols)
                rk = ranks(s)
                pb = boot_p1(X[dom_rows[d]], tr, cols)
                out.append({"assay": a, "metric": metric, "loci": d, "top": s.idxmax(),
                            "P_boot(top #1)": pb[s.idxmax()], "eye rank": rk["eye"],
                            "kidney rank": rk["kidney"], "of": len(s),
                            "liver rank": rk.get("liver", np.nan)})
    e4 = pd.DataFrame(out)
    e4.to_csv(os.path.join(EN, "step48_within_assay.csv"), index=False)
    L += ["## E4. Calibrated, within one assay", "", e4.round(3).to_markdown(index=False), ""]

    # E5 max per tissue
    mx = []
    ntr = tr.iloc[keep].groupby("tissue").size()
    for a, cols in [("all", keep), ("DNASE", keep[tr.iloc[keep].assay.values == "DNASE"])]:
        for d, m in dom_rows.items():
            s = max_per_tissue(P[m], tr, cols)
            n = tr.iloc[cols].groupby("tissue").size()[s.index]
            mx.append({"tracks": a, "loci": d, "Spearman(max, n tracks)": spearmanr(s, n).correlation,
                       "top": s.idxmax(), "top n tracks": int(n[s.idxmax()]), "eye rank": ranks(s)["eye"],
                       "eye n tracks": int(n["eye"])})
    e5 = pd.DataFrame(mx)
    e5.to_csv(os.path.join(EN, "step48_max_per_tissue.csv"), index=False)
    L += ["## E5. Max over each tissue's tracks (calibrated)", "", e5.round(3).to_markdown(index=False), ""]

    with open(REPORT, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {REPORT}")


if __name__ == "__main__":
    main()
