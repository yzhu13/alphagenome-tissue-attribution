"""
step46_grouping_sensitivity.py

Do the conclusions depend on our grouping of AlphaGenome biosamples into 13
tissue categories? Two alternatives:

  A. 9 organ systems: gut + liver + pancreas/islet -> digestive; muscle/adipose + skin ->
     musculoskeletal/skin; eye, brain, heart/vascular, kidney, immune, lung, reproductive unchanged
     (`other` excluded; the misfiled choroid plexus track is folded into eye for the raw (original pipeline)
     method and excluded from the calibrated methods, as in the main analysis).
  B. No grouping: every biosample (ontology term) is its own unit.

For A, the eye's rank under the four comparisons of Fig. 4a. For B, whether units made only of
chromatin tracks rise to the top under raw pooling (Spearman with each unit's chromatin share, and the
rank of the ocular biosamples), and what happens after calibration within DNase.

Uses the step42 matrix cache. Writes reports/grouping_sensitivity.md and data/analysis/step46_*.csv.

    python scripts/step46_grouping_sensitivity.py
"""
import os
import sys

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import step35_analysis as s35  # noqa: E402
import step42_uncertainty as s42  # noqa: E402

REPORT = os.path.join(s35.NEW, "reports", "grouping_sensitivity.md")
SYSTEMS = {"gut": "digestive", "liver": "digestive", "pancreas_islet": "digestive",
           "muscle_adipose": "musculoskeletal/skin", "skin": "musculoskeletal/skin"}
OCULAR = {"CL:0002565": "iris pigment epithelium", "CL:0002586": "retinal pigment epithelium",
          "CL:0002304": "non-pigmented ciliary epithelium", "UBERON:0000966": "retina (embryonic)",
          "CL:0000706": "choroid plexus (misfiled)"}


def col_meta(cols):
    cat = pd.read_csv(s35.CATALOG).drop_duplicates("name").set_index("name")
    names = [c.split("|")[1] for c in cols]
    m = pd.DataFrame({"col": cols, "name": names,
                      "assay": [c.split("|")[0].split("_")[0] for c in cols],
                      "tissue": [cat.tissue_category.get(n, "other") for n in names],
                      "biosample": [cat.ontology_curie.get(n, n) for n in names]})
    m.loc[(m.tissue == "eye") & (m.biosample == "CL:0000706"), "tissue"] = "eye_misfiled"
    return m


def unit_scores(X, units):
    colmean = np.nanmean(X, axis=0)
    return pd.Series({u: colmean[units == u].mean() for u in pd.unique(units)})


def rank_of(s, key):
    return int(s.rank(ascending=False, method="min")[key])


def main():
    M = s42.build_matrices()
    v = s35.read_variants()
    dom = s35.domain_map(v)
    sets = {d: set(dom.loc[dom.domain == d, "id"]) for d in ["eye", "kidney", "metabolic", "null"]}
    L = ["# Tissue-grouping sensitivity", "", "Generated by `scripts/step46_grouping_sensitivity.py`.", ""]

    # A. organ systems
    methods = [("raw, pooled (original pipeline)", "raw", None, True, None),
               ("calibrated, pooled (null pct)", "emp_rec", None, False, None),
               ("calibrated DNase, mean |q|", "q", "dnase", False, None),
               ("calibrated DNase, strong fraction", "q", "dnase", False, 0.95)]
    rows = []
    for lab, key, assay, pub, thr in methods:
        X, ids, cols = M[f"{key}_X"], M[f"{key}_ids"], M[f"{key}_cols"]
        m = col_meta(cols)
        keep = (m.assay == assay) if assay else np.ones(len(m), bool)
        t = m.tissue.replace({"eye_misfiled": "eye"}) if pub else m.tissue
        ok = keep & ~t.isin(["other", "eye_misfiled"])
        sys_units = t[ok].replace(SYSTEMS).values
        Xk = X[:, ok.values]
        if thr is not None:
            Xk = (Xk >= thr).astype("float32")
        for d, idset in sets.items():
            if d == "null" and key != "raw":
                continue  # calibrated scores are ~0.5 for null by construction
            s = unit_scores(Xk[np.isin(ids, list(idset))], sys_units)
            rows.append({"method": lab, "loci": d, "eye rank": rank_of(s, "eye"), "of": len(s),
                         "top": s.idxmax()})
    a = pd.DataFrame(rows)
    a.to_csv(os.path.join(s35.AN, "step46_organ_systems.csv"), index=False)
    L += ["## A. Nine organ systems instead of 13 tissue categories", "",
          a.pivot(index="method", columns="loci", values="eye rank").to_markdown(), "",
          "Top system per method and loci:", "", a.pivot(index="method", columns="loci", values="top").to_markdown(), ""]

    # B. biosample level
    X, ids, cols = M["raw_X"], M["raw_ids"], M["raw_cols"]
    m = col_meta(cols)
    ok = (m.tissue != "other").values
    m, Xr = m[ok].reset_index(drop=True), X[:, ok]
    chrom = m.groupby("biosample").assay.apply(lambda a: a.isin(["dnase", "atac"]).mean())
    ntr = m.groupby("biosample").size()
    brow = []
    for d in ["eye", "kidney", "metabolic", "null"]:
        s = unit_scores(Xr[np.isin(ids, list(sets[d]))], m.biosample.values)
        pr = s.rank(ascending=False, pct=True)
        top20 = s.sort_values(ascending=False).head(20).index
        row = {"loci": d, "biosamples": len(s), "Spearman(score, chromatin share)": spearmanr(s, chrom[s.index]).correlation,
               "chromatin share, top 20": chrom[top20].mean(), "chromatin share, all": chrom[s.index].mean()}
        for curie, name in OCULAR.items():
            if curie in s.index:
                row[f"{name} (top %)"] = round(100 * pr[curie], 1)
        brow.append(row)
    b = pd.DataFrame(brow)
    b.to_csv(os.path.join(s35.AN, "step46_biosample_raw.csv"), index=False)
    L += ["## B. No grouping: each biosample is its own unit (raw scores, pooled over its assays)", "",
          f"{m.biosample.nunique()} biosamples outside `other`; a biosample's chromatin share = fraction of its "
          "tracks that are DNase or ATAC. `top %` = the ocular biosample's percentile from the top (smaller = higher).", "",
          b.round(3).to_markdown(index=False), ""]

    # B'. biosample level, DNase only, calibrated: where do the ocular biosamples sit?
    X, ids, cols = M["q_X"], M["q_ids"], M["q_cols"]
    m = col_meta(cols)
    ok = ((m.assay == "dnase") & (m.tissue != "other")).values
    m, Xq = m[ok].reset_index(drop=True), X[:, ok]
    crow = []
    for d in ["eye", "kidney", "metabolic", "null"]:
        s = unit_scores((Xq[np.isin(ids, list(sets[d]))] >= 0.95).astype("float32"), m.biosample.values)
        pr = s.rank(ascending=False, pct=True)
        row = {"loci": d, "DNase biosamples": len(s)}
        for curie, name in OCULAR.items():
            if curie in s.index:
                row[f"{name} (top %)"] = round(100 * pr[curie], 1)
        crow.append(row)
    c = pd.DataFrame(crow)
    c.to_csv(os.path.join(s35.AN, "step46_biosample_dnase_calibrated.csv"), index=False)
    L += ["## B'. No grouping, calibrated DNase only (strong-effect fraction, |q| >= 0.95)", "",
          c.to_markdown(index=False), ""]

    with open(REPORT, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {REPORT}")


if __name__ == "__main__":
    main()
