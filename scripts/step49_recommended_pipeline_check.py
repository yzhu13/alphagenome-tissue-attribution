"""
step49_recommended_pipeline_check.py

Checks the recommended pipeline. Box 2 recommends: DNase only, calibrate against a gene-distance-matched null,
summarise by the strong-effect fraction, report uncertainty over loci and tracks. Under the matched
null the eye ranked first for eye AND metabolic loci (reports/matched_null.md c). Is that a residual
eye "hub" or the noise of a four-track tissue?

  1. Eye rank per domain under the full recommended pipeline (and the variants: random null,
     AlphaGenome |q|; mean vs strong fraction), with a joint bootstrap over loci and tracks.
  2. Fake-eye test: 5,000 random sets of four DNase tracks from the other 11 tissues; how often does
     such a set rank first, and where does the real eye fall in the distribution of fake-eye scores?
  3. Specificity (tissue x domain): each tissue's score for one domain minus its mean score for the
     other two domains. This removes tissue-wide track properties (e.g. insensitivity to gene
     proximity) that lift a tissue for every trait. Joint bootstrap over loci within domain and tracks.
  4. One table of the eye's rank under every method (Supplementary Table 1).

Writes reports/recommended_pipeline_check.md and data/analysis/step49_*.csv.

    python scripts/step49_recommended_pipeline_check.py
"""
import glob
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import step35_analysis as s35  # noqa: E402
import step42_uncertainty as s42  # noqa: E402

MATCH_RUN = os.path.join(s35.NEW, "data", "null_matched_scoring")
CACHE = os.path.join(s35.NEW, "data", "uncertainty", "dnase_matched_null.npz")
REPORT = os.path.join(s35.NEW, "reports", "recommended_pipeline_check.md")
N_BOOT, N_FAKE, SEED, THR = 500, 5000, 20260923, 0.95
DOMAINS = ["eye", "kidney", "metabolic"]


def dnase_matched_matrix():
    """GWAS loci x DNase tracks (recommended scorer): percentile of |q| among the matched null."""
    if os.path.exists(CACHE):
        z = np.load(CACHE, allow_pickle=True)
        return z["X"], z["ids"], z["cols"]
    m = pd.read_csv(os.path.join(MATCH_RUN, "variants.csv"), keep_default_na=False)
    index, G = s35.null_grids(sorted(glob.glob(os.path.join(MATCH_RUN, "parts", "*.parquet"))), set(m.id))
    v = s35.read_variants()
    gwas = set(v.id[v.set == "gwas"])
    mats = []
    for p in sorted(glob.glob(os.path.join(s35.RUN, "parts", "*.parquet"))):
        d = pd.read_parquet(p)
        d = d[(d.scorer == "dnase_rec") & d.id.isin(gwas)]
        if not len(d):
            continue
        d["emp"] = s35.empirical(d, index, G)
        k = d.groupby(["id", "scorer", "track_name"]).cumcount().astype(str)
        d["col"] = d.scorer + "|" + d.track_name + "|" + k
        mats.append(d.pivot_table(index="id", columns="col", values="emp", aggfunc="first"))
    M = pd.concat(mats)
    X, ids, cols = M.values.astype("float32"), M.index.values.astype(str), M.columns.values.astype(str)
    np.savez_compressed(CACHE, X=X, ids=ids, cols=cols)
    return X, ids, cols


def dnase_only(X, ids, cols):
    keep = np.array([c.startswith("dnase_rec|") for c in cols])
    X, cols = X[:, keep], cols[keep]
    tis = s42.col_tissue(cols, published_eye=False)
    ok = ~np.isin(tis, ["other", "eye_misfiled"])
    return X[:, ok], ids, tis[ok]


def tissue_scores(colmean, tis, tissues):
    return np.array([colmean[tis == t].mean() for t in tissues])


def main():
    rng = np.random.default_rng(SEED)
    M = s42.build_matrices()
    v = s35.read_variants()
    dom = s35.domain_map(v)
    rows_of = {d: set(dom.loc[dom.domain == d, "id"]) for d in DOMAINS}
    Xm, idm, colm = dnase_matched_matrix()
    variants = {
        "AlphaGenome |q| (common-variant background)": dnase_only(M["q_X"], M["q_ids"], M["q_cols"]),
        "null pct, random null": dnase_only(M["emp_rec_X"], M["emp_rec_ids"], M["emp_rec_cols"]),
        "null pct, matched null": dnase_only(Xm, idm, colm),
    }
    L = ["# Does the recommended pipeline still show an eye hub?", "",
         "Generated by `scripts/step49_recommended_pipeline_check.py`. DNase tracks of the recommended "
         "scorer only; 12 tissues (eye = 4 tracks; choroid plexus excluded). Strong fraction = share of "
         f"(locus, track) pairs >= {THR}. Joint bootstrap: {N_BOOT} resamples of loci and of tracks within tissue.",
         ""]

    # 1 + 2
    out1, out2 = [], []
    for vname, (X, ids, tis) in variants.items():
        tissues = np.unique(tis)
        eye_i = int(np.where(tissues == "eye")[0][0])
        others = np.where(tis != "eye")[0]
        for metric in ["mean", "strong fraction"]:
            Y = X if metric == "mean" else (X >= THR).astype("float32")
            for d in DOMAINS:
                Yd = Y[np.isin(ids, list(rows_of[d]))]
                Yd = np.nan_to_num(Yd, nan=np.nanmean(Yd))
                t_, obs, R = s42.boot_ranks(Yd, tis, N_BOOT, rng)
                s = s42.summarise(t_, obs, R).set_index("tissue")
                top = s["rank"].idxmin()
                out1.append({"calibration": vname, "metric": metric, "loci": d, "eye rank": int(s.loc["eye", "rank"]),
                             "eye P(#1)": s.loc["eye", "p_rank1"],
                             "eye 95% rank": f"{s.loc['eye', 'rank_lo']:.0f}-{s.loc['eye', 'rank_hi']:.0f}",
                             "top": top, "top P(#1)": s.loc[top, "p_rank1"],
                             "expected (kidney) rank": int(s.loc["kidney", "rank"]) if d == "kidney" else np.nan})
                # fake eye: 4 random DNase tracks from the other tissues
                colmean = Yd.mean(0)
                real = tissue_scores(colmean, tis, tissues)
                rest = np.delete(real, eye_i)
                fake = np.array([colmean[rng.choice(others, 4, replace=False)].mean() for _ in range(N_FAKE)])
                out2.append({"calibration": vname, "metric": metric, "loci": d,
                             "eye score": real[eye_i], "fake-eye median": np.median(fake),
                             "eye percentile among fakes": (fake < real[eye_i]).mean(),
                             "P(fake eye ranks #1)": (fake > rest.max()).mean()})
    t1, t2 = pd.DataFrame(out1), pd.DataFrame(out2)
    t1.to_csv(os.path.join(s35.AN, "step49_eye_rank_recommended.csv"), index=False)
    t2.to_csv(os.path.join(s35.AN, "step49_fake_eye.csv"), index=False)
    L += ["## 1. Eye rank under each calibration and summary", "", t1.round(3).to_markdown(index=False), "",
          "## 2. Fake-eye test (random 4-track DNase sets from the other tissues)", "",
          "`eye percentile among fakes` near 1 = the real eye tracks respond more than random 4-track sets; "
          "`P(fake eye ranks #1)` = how often a random 4-track set would beat all 11 real non-eye tissues.", "",
          t2.round(3).to_markdown(index=False), ""]

    # 3 specificity: tissue score for domain d minus mean over the other two domains
    out3, out_all = [], []
    for vname, (X, ids, tis) in variants.items():
        tissues = np.unique(tis)
        groups = [np.where(tis == t)[0] for t in tissues]
        for metric in ["mean", "strong fraction"]:
            Y = X if metric == "mean" else (X >= THR).astype("float32")
            Y = np.nan_to_num(Y, nan=np.nanmean(Y))
            rows = {d: np.where(np.isin(ids, list(rows_of[d])))[0] for d in DOMAINS}
            cm = {d: Y[r].mean(0) for d, r in rows.items()}

            def spec(cmd, pick):
                sc = {d: np.array([cmd[d][g].mean() for g in pick]) for d in DOMAINS}
                return {d: sc[d] - np.mean([sc[e] for e in DOMAINS if e != d], axis=0) for d in DOMAINS}

            obs = spec(cm, groups)
            B = {d: [] for d in DOMAINS}
            for _ in range(N_BOOT):
                cmb = {d: Y[rng.choice(r, len(r))].mean(0) for d, r in rows.items()}
                pick = [rng.choice(g, len(g)) for g in groups]
                sb = spec(cmb, pick)
                for d in DOMAINS:
                    B[d].append(sb[d])
            for d in DOMAINS:
                Bd = np.array(B[d])
                rk = (-obs[d]).argsort().argsort() + 1
                Rb = (-Bd).argsort(1).argsort(1) + 1
                for i, tname in enumerate(tissues):
                    out_all.append({"calibration": vname, "metric": metric, "loci": d, "tissue": tname,
                                    "n_tracks": len(groups[i]), "specificity": obs[d][i],
                                    "CI lo": np.percentile(Bd[:, i], 2.5), "CI hi": np.percentile(Bd[:, i], 97.5),
                                    "rank": int(rk[i]), "P(#1)": (Rb[:, i] == 1).mean()})
                expect = {"eye": "eye", "kidney": "kidney", "metabolic": None}[d]
                for tname in ([expect] if expect else []) + ["eye", tissues[rk.argmin()]]:
                    i = int(np.where(tissues == tname)[0][0])
                    out3.append({"calibration": vname, "metric": metric, "loci": d, "tissue": tname,
                                 "specificity": obs[d][i], "CI lo": np.percentile(Bd[:, i], 2.5),
                                 "CI hi": np.percentile(Bd[:, i], 97.5), "rank": int(rk[i]),
                                 "P(#1)": (Rb[:, i] == 1).mean(), "top": tissues[rk.argmin()]})
    t3 = pd.DataFrame(out3).drop_duplicates(["calibration", "metric", "loci", "tissue"])
    t3.to_csv(os.path.join(s35.AN, "step49_specificity.csv"), index=False)
    pd.DataFrame(out_all).to_csv(os.path.join(s35.AN, "step49_specificity_all.csv"), index=False)
    L += ["## 3. Specificity: tissue score for one domain minus its mean for the other two domains", "",
          "Positive = the tissue responds more to this domain's loci than to the other domains' loci. Tissue-wide "
          "track properties cancel. Rank among 12 tissues; bootstrap over loci within domain and tracks within tissue.",
          "", t3.round(4).to_markdown(index=False), ""]
    L += supp_table1()
    with open(REPORT, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {REPORT}")


def supp_table1():
    """Supplementary Table 1: the eye's rank among 12 tissues under every method, from the tables above
    and the matched-null analysis (step39b). Returns report lines."""
    c = pd.read_csv(os.path.join(s35.NEW, "data", "null_matched_analysis", "c_rankings.csv"))
    c = c[(c.tissue == "eye") & c.method.str.contains("pooled")]
    names = {"raw pooled (orig scorers, |raw|, original pipeline)": "Raw, all assays pooled",
             "calibrated pooled, random null (rec scorers)": "Calibrated, all assays pooled, random null",
             "calibrated pooled, matched null (rec scorers)": "Calibrated, all assays pooled, matched null"}
    pooled = c.pivot(index="method", columns="domain", values="rank").rename(index=names).loc[list(names.values())]
    t1 = pd.read_csv(os.path.join(s35.AN, "step49_eye_rank_recommended.csv"))
    dn = t1.pivot_table(index=["calibration", "metric"], columns="loci", values="eye rank")
    dn.index = [f"Calibrated, DNase only, {cal}, {met}" for cal, met in dn.index]
    t3 = pd.read_csv(os.path.join(s35.AN, "step49_specificity.csv"))
    sp = t3[t3.tissue == "eye"].drop_duplicates(["calibration", "metric", "loci"]).pivot_table(
        index=["calibration", "metric"], columns="loci", values="rank")
    sp.index = [f"Specificity contrast, DNase only, {cal}, {met}" for cal, met in sp.index]
    st = pd.concat([pooled, dn, sp])[DOMAINS].astype(int)
    st.index.name = "method"
    st.columns = [f"eye rank, {d} loci" for d in DOMAINS]
    st.to_csv(os.path.join(s35.AN, "step49_supp_table_eye_ranks.csv"))
    return ["## 4. The eye's rank among 12 tissues under every method (Supplementary Table 1)", "",
            st.to_markdown(), ""]


if __name__ == "__main__":
    main()
