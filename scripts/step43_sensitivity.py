"""
step43_sensitivity.py

Sensitivity of the main results to two analysis choices.

3. RNA statistic. The recommended RNA-seq scorer is gene-level; we kept the gene with the largest
   |q| per track ("max over genes"). One can ask whether the RNA > DNase excess of GWAS loci,
   which re-confounds pooled calibrated rankings, is created by that choice. The original scorer's
   RNA-seq output is a local, gene-agnostic statistic (501 bp around the variant, mean difference, no
   max over genes). We compare the two, each null-calibrated per track:
     a. GWAS excess over the null per assay, both RNA statistics, random and matched null;
     b. RNA-only tissue rankings per domain under the two statistics;
     c. pooled null-calibrated rankings built only from the local (original-scorer) statistics.
4. The original pipeline on the gene-distance-matched null: does it also rank the eye first?

Uses the matrix cache from step42 (random-null calibration) and reads the matched-null run
(data/null_matched_scoring) read-only. Writes reports/sensitivity.md.

    python scripts/step43_sensitivity.py
"""
import glob
import os
import sys

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import step35_analysis as s35  # noqa: E402
import step42_uncertainty as s42  # noqa: E402

REPORT = os.path.join(s35.NEW, "reports", "sensitivity.md")
MATCHED = os.path.join(s35.NEW, "data", "null_matched_scoring")
MATCHED_ANALYSIS = os.path.join(s35.NEW, "reports", "matched_null.md")


def tissue_means(X, tis):
    colmean = np.nanmean(X, axis=0)
    return pd.Series({t: colmean[tis == t].mean() for t in np.unique(tis)})


def main():
    M = s42.build_matrices()
    atac = pd.read_csv(s35.LOCI)
    dom_ids = {d: set(atac.loc[atac.disease_class == d, "rsid"]) for d in ["eye", "kidney", "metabolic"]}
    L = ["# Sensitivity analyses", "", "Generated by `scripts/step43_sensitivity.py`.", ""]

    # 3a. excess over null per assay and RNA statistic (random null; matched-null values from step39b)
    L += ["## 3a. GWAS excess over the null: gene-level (max over genes) vs local RNA statistic", "",
          "Mean null-percentile of GWAS loci (null = 0.50). *Recommended* = AlphaGenome recommended scorers "
          "(RNA: gene-level, max |q| over genes per track). *Original* = 501-bp DIFF_MEAN scorers (RNA: local "
          "coverage change at the variant, gene-agnostic). Matched-null column from `reports/matched_null.md`.", ""]
    rows = []
    for key, fam in [("emp_rec", "recommended"), ("emp_orig", "original")]:
        X, ids, cols = M[f"{key}_X"], M[f"{key}_ids"], M[f"{key}_cols"]
        g = np.isin(ids, list(set().union(*dom_ids.values())))
        for assay in ["dnase", "atac", "rna"]:
            c = np.array([x.startswith(assay + "_") for x in cols])
            rows.append({"scorers": fam, "assay": assay, "vs random null": float(np.nanmean(X[g][:, c]))})
    t3a = pd.DataFrame(rows)
    try:  # attach matched-null numbers from step39b's report table
        mt = pd.read_csv(os.path.join(s35.NEW, "data", "null_matched_analysis", "b_assay_percentiles.csv"))
        m = mt[mt.variants == "gwas"].set_index("scorer")["mean pct vs matched null"]
        t3a["vs matched null"] = [m.get(f"{a}_{'rec' if f == 'recommended' else 'orig'}", np.nan)
                                  for f, a in zip(t3a.scorers, t3a.assay)]
    except Exception as e:
        L.append(f"(matched-null column unavailable: {e})")
    piv = t3a.pivot(index="assay", columns="scorers")
    L += [piv.round(3).to_markdown(), ""]
    for fam in ["recommended", "original"]:
        s = t3a[t3a.scorers == fam].set_index("assay")["vs random null"]
        L.append(f"- {fam}: RNA − DNase = {s['rna'] - s['dnase']:+.3f} (random null)")
    L.append("")

    # 3b. RNA-only rankings under the two statistics
    L += ["## 3b. RNA-only tissue rankings: gene-level vs local statistic (null-calibrated)", ""]
    rows = []
    for d, ids in dom_ids.items():
        ser = {}
        for key, sc, lab in [("emp_rec", ["rna_rec"], "gene-level"), ("emp_orig", ["rna_orig"], "local")]:
            X, rid, tis = s42.select(M, key, sc, False)
            ser[lab] = tissue_means(X[np.isin(rid, list(ids))], tis)
        both = pd.concat(ser, axis=1).dropna()
        rows.append({"domain": d, "tissues": len(both),
                     "Spearman(gene-level, local)": spearmanr(both["gene-level"], both["local"]).correlation,
                     "top (gene-level)": both["gene-level"].idxmax(), "top (local)": both["local"].idxmax()})
    L += [pd.DataFrame(rows).round(3).to_markdown(index=False), ""]

    # 3c. pooled calibrated rankings from the local statistics only
    L += ["## 3c. Pooled null-calibrated ranking using only the original (local) scorers", "",
          "If pooling re-confounds only because of our max-over-genes RNA statistic, this should fix it.", ""]
    rows = []
    for d, ids in dom_ids.items():
        X, rid, tis = s42.select(M, "emp_orig", s35.ORIG, False)
        s = tissue_means(X[np.isin(rid, list(ids))], tis).sort_values(ascending=False)
        rows.append({"domain": d, "eye rank": list(s.index).index("eye") + 1, "of": len(s),
                     "top 3": ", ".join(s.index[:3])})
    L += [pd.DataFrame(rows).to_markdown(index=False), ""]

    # 4. original pipeline on the matched null
    L += ["## 4. Original pipeline (raw, pooled, eye as in the original pipeline) on the two null sets", ""]
    rows = []
    v = s35.read_variants()
    null_ids = set(v.id[v.set == "null"])
    X, rid, tis = s42.select(M, "raw", s35.ORIG, True, exclude=("other",))
    s = tissue_means(X[np.isin(rid, list(null_ids))], tis).sort_values(ascending=False)
    rows.append({"null set": "random (2,000)", "eye rank": list(s.index).index("eye") + 1, "of": len(s),
                 "eye / next": s.iloc[0] / s.iloc[1] if s.index[0] == "eye" else np.nan, "top 3": ", ".join(s.index[:3])})
    parts = sorted(glob.glob(os.path.join(MATCHED, "parts", "*.parquet")))
    if parts:
        d = pd.concat(pd.read_parquet(p) for p in parts)
        d = d[d.scorer.isin(s35.ORIG)]
        d["tissue"] = d.track_name.map(s35.track_map()).fillna("other").replace({"eye_misfiled": "eye"})
        d = d[d.tissue != "other"]
        per_track = d.groupby(["track_name", "tissue"]).raw_score.apply(lambda z: z.abs().mean()).reset_index()
        s = per_track.groupby("tissue").raw_score.mean().sort_values(ascending=False)
        rows.append({"null set": f"gene-distance matched ({d.id.nunique():,})", "eye rank": list(s.index).index("eye") + 1,
                     "of": len(s), "eye / next": s.iloc[0] / s.iloc[1] if s.index[0] == "eye" else np.nan,
                     "top 3": ", ".join(s.index[:3])})
    L += [pd.DataFrame(rows).round(2).to_markdown(index=False), ""]

    with open(REPORT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"wrote {REPORT}")


if __name__ == "__main__":
    main()
