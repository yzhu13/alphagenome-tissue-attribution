"""
step36_benchmark_expected_tissue.py

Benchmark B1, qualitative version. For traits whose disease-relevant tissue is
well established by independent heritability-enrichment studies, where does that tissue rank
among the 13 tissue categories under (a) the original raw pipeline and (b) calibrated scores?
A method that tracks biology should put the expected tissue near the top.

Expected tissues and their sources (primary set):
  BMI                       -> brain           Finucane 2015 Nat Genet; Finucane 2018 Nat Genet (CNS)
  LDL, HDL, triglycerides   -> liver           Finucane 2015; Finucane 2018
  T2D                       -> pancreas_islet  Pasquali 2014 Nat Genet; Chiou 2021 Nat Genet (islet chromatin)
  hypertension              -> heart_vascular  Finucane 2018 (blood pressure: cardiovascular / arterial)
  eGFR, CKD, UACR           -> kidney          Wuttke 2019 Nat Genet; Teumer 2019 Nat Commun
Secondary set (ocular traits; the relevant ocular tissue is plausible but less settled):
  glaucoma, IOP, myopia     -> eye
AMD, cataract and diabetic retinopathy are left out: independent evidence points to several
tissues (e.g. complement / liver for AMD), so there is no single expected tissue.

Reads data/analysis/locus_tissue.parquet (written by step35). Writes
reports/benchmark_expected_tissue.md and data/analysis/B1_expected_tissue_ranks.csv.

    python scripts/step36_benchmark_expected_tissue.py
"""
import os
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import step35_analysis as s35  # noqa: E402  (shared paths, aggregation and the original-pipeline fold)

EXPECTED = {
    "BMI": "brain", "LDL": "liver", "HDL": "liver", "triglycerides": "liver",
    "T2D": "pancreas_islet", "hypertension": "heart_vascular",
    "eGFR": "kidney", "CKD": "kidney", "UACR": "kidney",
}
EXPECTED_SECONDARY = {"glaucoma": "eye", "IOP": "eye", "myopia": "eye"}
# "other" is a catch-all bin and eye_misfiled is one brain-ventricle track: neither is a tissue.
NOT_TISSUES = {"other", "eye_misfiled"}

METHODS = [  # label, frame ("pub" = eye folded as in the original pipeline), scorer, column
    ("raw, original pipeline", "pub", "orig_all", "abs_raw"),
    ("calibrated DNase |q|", "lt", "dnase_rec", "abs_q"),
    ("calibrated DNase top-5%", "lt", "dnase_rec", "top5"),
    ("null-calibrated, recommended all assays", "lt", "rec_all", "emp"),
    ("null-calibrated, ORIGINAL scorer", "lt", "orig_all", "emp"),
]
OUT = os.path.join(s35.NEW, "reports", "benchmark_expected_tissue.md")


def main():
    lt, _ = s35.aggregate()
    frames = {"lt": lt, "pub": s35.as_published(lt)}
    traits = pd.read_csv(s35.LOCI)[["rsid", "source_disease"]].drop_duplicates()
    rows = []
    for trait, tissue in {**EXPECTED, **EXPECTED_SECONDARY}.items():
        ids = traits.loc[traits.source_disease == trait, "rsid"]
        for label, fk, scorer, col in METHODS:
            x = frames[fk]
            x = x[(x.scorer == scorer) & x.id.isin(ids) & ~x.tissue.isin(NOT_TISSUES)]
            if x.empty:
                continue
            m = x.groupby("tissue")[col].mean().sort_values(ascending=False)
            rows.append({"trait": trait, "expected": tissue, "set": "primary" if trait in EXPECTED else "secondary",
                         "method": label, "n_loci": x.id.nunique(),
                         "rank": list(m.index).index(tissue) + 1 if tissue in m.index else None,
                         "of": len(m), "top_tissue": m.index[0]})
    r = pd.DataFrame(rows)
    os.makedirs(s35.AN, exist_ok=True)
    r.to_csv(os.path.join(s35.AN, "B1_expected_tissue_ranks.csv"), index=False)

    L = ["# B1 (qualitative): rank of the independently expected tissue", "",
         "Generated by `scripts/step36_benchmark_expected_tissue.py`. Rank 1 = the method puts the "
         "expected tissue first among the 12 named tissue categories (`other` and the misfiled choroid "
         "plexus track excluded). Sources for the expected tissues are in the script header.", ""]
    if r.empty:
        L.append("No GWAS loci scored yet.")
    else:
        for s in ["primary", "secondary"]:
            sub = r[r.set == s]
            if sub.empty:
                continue
            piv = sub.pivot_table(index=["trait", "expected", "n_loci"], columns="method", values="rank")
            piv = piv[[m[0] for m in METHODS if m[0] in piv.columns]]
            L += [f"## {s.capitalize()} set: rank of expected tissue", "", piv.to_markdown(), ""]
            summ = sub.groupby("method").agg(mean_rank=("rank", "mean"),
                                             n_top1=("rank", lambda z: int((z == 1).sum())),
                                             n_top3=("rank", lambda z: int((z <= 3).sum())),
                                             n_traits=("rank", "size"))
            L += [f"### {s.capitalize()} set: summary", "", summ.round(2).to_markdown(), ""]
        top = r.pivot_table(index="trait", columns="method", values="top_tissue", aggfunc="first")
        L += ["## Which tissue each method puts first", "", top.to_markdown(), ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
